/// Keeps the selected content language below the app navigator so changing
/// language cannot replace or clear the active route.
class OylaLanguageScope extends InheritedWidget {
  const OylaLanguageScope({
    super.key,
    required this.language,
    required super.child,
  });

  final AppLanguage language;

  @override
  bool updateShouldNotify(OylaLanguageScope oldWidget) =>
      language != oldWidget.language;
}

class _OylaLocalizationsDelegate
    extends LocalizationsDelegate<OylaLocalizations> {
  const _OylaLocalizationsDelegate();
  @override
  bool isSupported(Locale locale) =>
      const {'en', 'kk', 'ru'}.contains(locale.languageCode);
  @override
  Future<OylaLocalizations> load(Locale locale) async =>
      OylaLocalizations(switch (locale.languageCode) {
        'kk' => AppLanguage.kazakh,
        'ru' => AppLanguage.russian,
        _ => AppLanguage.english,
      });
  @override
  bool shouldReload(covariant LocalizationsDelegate<OylaLocalizations> old) =>
      false;
}

extension OylaStringsContext on BuildContext {
  OylaLocalizations get strings => OylaLocalizations.of(this);
}
