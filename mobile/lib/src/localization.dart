  static OylaLocalizations of(BuildContext context) {
    final scoped = context
        .dependOnInheritedWidgetOfExactType<OylaLanguageScope>();
    return scoped == null
        ? Localizations.of<OylaLocalizations>(context, OylaLocalizations) ??
              const OylaLocalizations(AppLanguage.english)
        : OylaLocalizations(scoped.language);
  }

  static const delegate = _OylaLocalizationsDelegate();

  String get localeCode => switch (language) {
    AppLanguage.english => 'en',
    AppLanguage.kazakh => 'kk',
    AppLanguage.russian => 'ru',
  };

  String text(String key) =>
      _values[language]?[key] ?? _values[AppLanguage.english]![key] ?? key;

  /// Explicit entries, exposed for translation coverage checks.
  Map<String, String> get translations => Map.unmodifiable(_values[language]!);

  String format(String key, Map<String, Object> values) {
    var result = text(key);
    for (final entry in values.entries) {
      result = result.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return result;
  }

  String exerciseLabel(ExerciseType type) => text('exercise.${type.name}');
  String exerciseInstruction(ExerciseType type) =>
      text('instruction.${type.name}');

